"""Demo content, so Balanza shows something useful the first time it opens.

Everything here is invented: the lender, the people and the loans.
"""
from __future__ import annotations

from datetime import date
from functools import lru_cache

from . import aiact, database
from .demo_model import build_demo, score_table
from .synthetic import generate, to_csv
from .validation import fingerprint, read_csv, run_monitoring, run_validation

DEMO_DATASET_NAME = "demo_credit_scored.csv"

# (drift, concept) for each of the 12 demo months: eight quiet months, then
# a downturn. Applicants carry more debt and the model starts to miss.
SCENARIO = [(0.0, 0.0)] * 7 + [(0.15, 0.05), (0.3, 0.15), (0.55, 0.3), (0.8, 0.5), (1.1, 0.7)]

DEMO_DOCS = {
    "intended_purpose": (
        "Supports the decision to grant unsecured personal loans between 1,000 and 60,000 euros to private "
        "individuals. It estimates the probability that the applicant will miss payments within 12 months. "
        "Credit analysts use the score; it is never shown to the customer as a final decision."
    ),
    "data_description": (
        "Demo data: 6,000 invented applications generated by code (balanza/synthetic.py). 70% is used to build "
        "the model and 30% is kept aside to test it. No real personal data. Gender and age are stored only to "
        "test for bias and are never given to the model."
    ),
    "design_choices": (
        "Logistic regression on seven inputs: income, years in current job, debt-to-income, credit utilisation, "
        "previous defaults, loan amount and loan term. Chosen because every weight can be read and explained. "
        "Loans are proposed for approval when the probability of default is below 15%."
    ),
    "human_oversight": (
        "A credit analyst reviews every rejection and every application scored between 10% and 20%. The analyst "
        "can overrule the model in both directions and must write the reason. Overrules are reviewed monthly by "
        "the head of credit risk."
    ),
    "logging": (
        "For each application the system stores the inputs, the score, the proposed decision, the model version, "
        "the analyst who reviewed it and the final decision. Records are kept for 6 years."
    ),
    # Left empty on purpose, so the demo shows what a gap looks like:
    "limitations": "",
    "risk_management": "",
    "monitoring_plan": "",
}


def demo_periods(count: int = 12, today: date | None = None) -> list[str]:
    """The last `count` full months, oldest first, as 'YYYY-MM'."""
    today = today or date.today()
    year, month = today.year, today.month
    periods = []
    for _ in range(count):
        month -= 1
        if month == 0:
            year, month = year - 1, 12
        periods.append(f"{year:04d}-{month:02d}")
    return periods[::-1]


@lru_cache(maxsize=1)
def _demo():
    return build_demo()


@lru_cache(maxsize=1)
def demo_dataset_csv() -> str:
    """The scored demo dataset, in the same CSV format a lender would upload."""
    _, scored = _demo()
    return to_csv(scored)


def demo_batch_csv(index: int) -> str:
    """One month of invented production loans, scored by the demo model."""
    model, _ = _demo()
    drift, concept = SCENARIO[index] if index < len(SCENARIO) else SCENARIO[-1]
    batch = score_table(model, generate(n=1500, seed=100 + index, drift=drift, concept=concept))
    return to_csv(batch)


def seed() -> None:
    """Fill an empty database with the demo inventory."""
    if database.count_models():
        return

    credit = aiact.USE_CASES["credit_scoring"]
    model_id = database.create_model(
        name="Consumer Credit Scorecard",
        owner="Model Risk, Demo Lender (fictional)",
        use_case="credit_scoring",
        risk_class=credit["risk_class"],
        risk_basis=credit["basis"],
        purpose="Probability of default for unsecured personal loans.",
        model_type="Logistic regression",
        version="1.0",
        docs=DEMO_DOCS,
    )
    text = demo_dataset_csv()
    result = run_validation(read_csv(text))
    database.add_validation(model_id, DEMO_DATASET_NAME, fingerprint(text), result)
    for index, period in enumerate(demo_periods(len(SCENARIO))):
        batch = demo_batch_csv(index)
        record = run_monitoring(read_csv(batch), result["reference_profile"], result["auc"], result["auc_se"])
        database.add_monitoring(model_id, period, fingerprint(batch), record)

    fraud = aiact.USE_CASES["fraud_detection"]
    database.create_model(
        name="Card Fraud Detector",
        owner="Payments, Demo Lender (fictional)",
        use_case="fraud_detection",
        risk_class=fraud["risk_class"],
        risk_basis=fraud["basis"],
        purpose="Flags card transactions that look like fraud for manual review.",
        model_type="Gradient boosted trees",
        version="3.2",
    )
    chatbot = aiact.USE_CASES["chatbot"]
    database.create_model(
        name="Customer Support Assistant",
        owner="Customer Care, Demo Lender (fictional)",
        use_case="chatbot",
        risk_class=chatbot["risk_class"],
        risk_basis=chatbot["basis"],
        purpose="Answers customer questions about products and account servicing.",
        model_type="Large language model (third party)",
        version="2026.2",
    )
